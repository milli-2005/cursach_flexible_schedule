function Clean-Text([string]$text) {
    return ($text -replace "[`r`a]", '').Trim()
}

function Get-ParaIndexExact($doc, [string]$text) {
    for ($i = 1; $i -le $doc.Paragraphs.Count; $i++) {
        if ((Clean-Text $doc.Paragraphs.Item($i).Range.Text) -eq $text) {
            return $i
        }
    }
    throw "Paragraph not found: $text"
}

function Replace-RangeWithText($doc, [int]$startIndex, [int]$endIndexExclusive, [string]$text, [double]$firstLineIndent = 35.45) {
    $start = $doc.Paragraphs.Item($startIndex).Range.Start
    $end = $doc.Paragraphs.Item($endIndexExclusive).Range.Start
    $range = $doc.Range($start, $end)
    $range.Text = $text.TrimEnd() + "`r"
    foreach ($p in $range.Paragraphs) {
        $p.Range.Font.Name = 'Times New Roman'
        $p.Range.Font.Size = 14
        $p.Range.ParagraphFormat.Alignment = $wdAlignParagraphJustify
        $p.Range.ParagraphFormat.FirstLineIndent = $firstLineIndent
        $p.Range.ParagraphFormat.SpaceAfter = 0
        $p.Range.ParagraphFormat.SpaceBefore = 0
        $p.Range.ParagraphFormat.LineSpacingRule = 0
    }
}

function Insert-BodyParagraph([ref]$rangeRef, [string]$text) {
    if ([string]::IsNullOrWhiteSpace($text)) {
        $rangeRef.Value.InsertAfter("`r")
    } else {
        $rangeRef.Value.InsertAfter($text.Trim() + "`r")
    }
    $rangeRef.Value.Start = $rangeRef.Value.End
    $rangeRef.Value.End = $rangeRef.Value.End
    $prev = $rangeRef.Value.Document.Paragraphs.Item($rangeRef.Value.Document.Range(0, $rangeRef.Value.Start).Paragraphs.Count)
    $prev.Range.Font.Name = 'Times New Roman'
    $prev.Range.Font.Size = 14
    $prev.Range.ParagraphFormat.Alignment = $wdAlignParagraphJustify
    $prev.Range.ParagraphFormat.FirstLineIndent = 35.45
    $prev.Range.ParagraphFormat.SpaceAfter = 0
    $prev.Range.ParagraphFormat.SpaceBefore = 0
}

function Insert-TableTitle([ref]$rangeRef, [string]$text) {
    $rangeRef.Value.InsertAfter($text.Trim() + "`r")
    $rangeRef.Value.Start = $rangeRef.Value.End
    $rangeRef.Value.End = $rangeRef.Value.End
    $prev = $rangeRef.Value.Document.Paragraphs.Item($rangeRef.Value.Document.Range(0, $rangeRef.Value.Start).Paragraphs.Count)
    $prev.Range.Font.Name = 'Times New Roman'
    $prev.Range.Font.Size = 14
    $prev.Range.ParagraphFormat.Alignment = $wdAlignParagraphJustify
    $prev.Range.ParagraphFormat.FirstLineIndent = 0
    $prev.Range.ParagraphFormat.SpaceAfter = 0
    $prev.Range.ParagraphFormat.SpaceBefore = 0
}

function Add-FormattedTable($doc, [ref]$rangeRef, $rows) {
    $table = $doc.Tables.Add($rangeRef.Value, $rows.Count, 3)
    $table.Style = $doc.Tables.Item(1).Style
    $table.Borders.Enable = 1
    $table.Rows.Alignment = 1
    $table.AllowAutoFit = $true

    for ($r = 0; $r -lt $rows.Count; $r++) {
        for ($c = 0; $c -lt 3; $c++) {
            $cell = $table.Cell($r + 1, $c + 1)
            $cell.Range.Text = $rows[$r][$c]
            $cell.Range.Font.Name = 'Times New Roman'
            $cell.Range.Font.Size = 14
            $cell.Range.ParagraphFormat.Alignment = $wdAlignParagraphJustify
            $cell.Range.ParagraphFormat.FirstLineIndent = 0
            $cell.Range.ParagraphFormat.SpaceAfter = 0
            $cell.Range.ParagraphFormat.SpaceBefore = 0
            if ($r -eq 0) {
                $cell.Range.Bold = 1
            } else {
                $cell.Range.Bold = 0
            }
        }
    }

    $rangeRef.Value.SetRange($table.Range.End, $table.Range.End)
    $rangeRef.Value.InsertAfter("`r")
    $rangeRef.Value.SetRange($rangeRef.Value.End, $rangeRef.Value.End)
}

